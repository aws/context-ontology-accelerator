from coa_common.datazone_forms import deserialize_form, serialize_form
from coa_common.domain_models import (
    BusinessMetadata,
    Column,
    EnrichmentSource,
    ReviewStatus,
    Table,
)
from coa_sources.api.database_routes import _apply_business_overrides  # noqa: I001
from coa_sources.database.enrichment.prompts import SYSTEM_PROMPT, build_system_prompt
from coa_sources.database.enrichment.table_enricher import (
    _apply_column_metadata,
    _apply_table_metadata,
    run,
)
from coa_sources.database.rescan import merge_rescan_table

_ALL = ["description", "synonyms", "glossaryTerms", "tags"]
_ENRICHER = "coa_sources.database.enrichment.table_enricher"


def _model_result() -> dict:
    return {
        "table": {
            "description": "受注テーブル",
            "synonyms": ["注文"],
            "glossary_terms": ["受注管理"],
            "tags": ["取引"],
        },
        "primary_key": {"columns": ["order_id"], "confidence": 0.9},
        "columns": [
            {
                "name": "order_id",
                "description": "受注の識別子",
                "synonyms": ["注文ID"],
                "glossary_terms": [],
                "tags": ["キー"],
                "confidence": 0.9,
            },
            {
                "name": "model_no",
                "description": "製品の型番",
                "synonyms": ["型式"],
                "glossary_terms": ["製品"],
                "tags": ["製品"],
                "confidence": 0.9,
            },
        ],
    }


def _table(**table_biz) -> Table:
    return Table(
        name="orders",
        database="sales",
        data_source_id="ds-1",
        business_metadata=BusinessMetadata(**table_biz),
        columns=[
            Column(name="order_id", data_type="bigint"),
            Column(
                name="model_no",
                data_type="string",
                business_metadata=BusinessMetadata(
                    description="Model number, e.g. FR-A840",
                    enrichment_source=EnrichmentSource.DETERMINISTIC,
                ),
            ),
        ],
    )


# ── Namespace language in the enrichment run ──────────────────────────


class TestRunUsesNamespaceLanguage:
    # Pass 2 (relationship inference) has its own prompt; only Pass 1 is under test.
    @patch("coa_sources.database.enrichment.relationship_inferrer.infer_relationships", return_value=[])
    @patch(f"{_ENRICHER}._write_enriched_assets")
    @patch(f"{_ENRICHER}.read_assets_for_datasource")
    @patch(f"{_ENRICHER}.BedrockClient")
    def _run(self, language, mock_client_cls, mock_read, _write, _pass2):
        mock_client_cls.return_value.invoke.return_value = BedrockInvocationResult(
            result=_model_result(), input_tokens=1, output_tokens=1, latency_ms=1.0
        )
        mock_read.return_value = [_table(), _table()]
        run("ds-1", "proj-1", "dom-1", "full", emitter=MagicMock(), namespace_language=language)
        return mock_client_cls.return_value.invoke.call_args_list

    def test_english_namespace_sends_the_main_system_prompt(self) -> None:
        calls = self._run("en")
        assert calls
        assert all(call.args[0] is SYSTEM_PROMPT for call in calls)

    def test_japanese_namespace_sends_the_instruction_on_every_call(self) -> None:
        calls = self._run("ja")
        assert calls
        assert all(call.args[0] == build_system_prompt("ja") for call in calls)
        # The untrusted schema (user message) is unchanged by the language and
        # still carries identifiers and source comments verbatim.
        user_prompt = calls[0].args[1]
        assert "Output language" not in user_prompt
        assert "model_no (string)  -- Model number, e.g. FR-A840" in user_prompt


# ── Enrichment adds markers ───────────────────────────────────────────


class TestEnrichmentMarksGeneratedFields:
    def test_regenerated_table_marks_every_non_empty_field(self) -> None:
        table = _table()
        _apply_table_metadata(table, _model_result())
        assert table.business_metadata.generated_fields == _ALL

    def test_empty_generated_field_is_not_marked(self) -> None:
        result = _model_result()
        result["columns"][0]["glossary_terms"] = []
        table = _table()
        _apply_column_metadata(table, result["columns"])
        assert table.columns[0].business_metadata.generated_fields == ["description", "synonyms", "tags"]

    def test_preserved_source_description_is_never_marked(self) -> None:
        table = _table()
        _apply_column_metadata(table, _model_result()["columns"])
        preserved = table.columns[1].business_metadata
        # The source comment is copied unchanged, not regenerated or translated.
        assert preserved.description == "Model number, e.g. FR-A840"
        assert preserved.enrichment_source == EnrichmentSource.DETERMINISTIC
        # Only the empty supplements the model filled in are COA-generated.
        assert preserved.generated_fields == ["synonyms", "glossaryTerms", "tags"]

    def test_steward_supplement_is_kept_and_unmarked(self) -> None:
        table = _table(
            description="Steward text",
            synonyms=["受注"],
            enrichment_source=EnrichmentSource.STEWARD_EDITED,
        )
        _apply_table_metadata(table, _model_result())
        biz = table.business_metadata
        assert biz.description == "Steward text"
        assert biz.synonyms == ["受注"]
        assert biz.generated_fields == ["glossaryTerms", "tags"]

    def test_unchanged_generated_supplement_keeps_its_marker(self) -> None:
        table = _table(
            description="Steward text",
            synonyms=["注文"],
            enrichment_source=EnrichmentSource.STEWARD_EDITED,
            generated_fields=["synonyms"],
        )
        _apply_table_metadata(table, _model_result())
        assert table.business_metadata.generated_fields == ["synonyms", "glossaryTerms", "tags"]

    def test_reviewed_ai_table_is_left_exactly_as_is(self) -> None:
        table = _table(
            description="承認済み",
            enrichment_source=EnrichmentSource.AI_GENERATED,
            review_status=ReviewStatus.APPROVED,
            generated_fields=["description"],
        )
        _apply_table_metadata(table, _model_result())
        assert table.business_metadata.description == "承認済み"
        assert table.business_metadata.generated_fields == ["description"]


# ── Steward edits clear markers ───────────────────────────────────────


class TestStewardEditClearsMarkers:
    def test_edited_field_loses_marker_others_keep_theirs(self) -> None:
        biz = BusinessMetadata(
            description="生成された説明",
            synonyms=["注文"],
            tags=["取引"],
            enrichment_source=EnrichmentSource.AI_GENERATED,
            generated_fields=["description", "synonyms", "tags"],
        )
        assert _apply_business_overrides(biz, {"synonyms": ["注文", "オーダー"]}) is True
        assert biz.generated_fields == ["description", "tags"]
        assert biz.enrichment_source == EnrichmentSource.STEWARD_EDITED

    def test_description_edit_clears_description_marker(self) -> None:
        biz = BusinessMetadata(description="生成", generated_fields=["description", "tags"], tags=["x"])
        _apply_business_overrides(biz, {"description": "スチュワードの説明"})
        assert biz.generated_fields == ["tags"]

    def test_no_op_edit_keeps_markers(self) -> None:
        biz = BusinessMetadata(synonyms=["注文"], generated_fields=["synonyms"])
        assert _apply_business_overrides(biz, {"synonyms": ["注文"]}) is False
        assert biz.generated_fields == ["synonyms"]


# ── Re-scan keeps only unchanged values' markers ──────────────────────


class TestRescanMarkers:
    def _accepted(self) -> Table:
        return Table(
            name="orders",
            database="sales",
            business_metadata=BusinessMetadata(
                description="生成された説明",
                synonyms=["注文"],
                enrichment_source=EnrichmentSource.AI_GENERATED,
                review_status=ReviewStatus.APPROVED,
                generated_fields=["description", "synonyms"],
            ),
            columns=[
                Column(
                    name="order_id",
                    data_type="bigint",
                    business_metadata=BusinessMetadata(
                        description="受注の識別子",
                        tags=["キー"],
                        enrichment_source=EnrichmentSource.AI_GENERATED,
                        review_status=ReviewStatus.APPROVED,
                        generated_fields=["description", "tags"],
                    ),
                )
            ],
        )

    def test_unchanged_values_keep_markers(self) -> None:
        fresh = Table(name="orders", database="sales", columns=[Column(name="order_id", data_type="bigint")])
        merged = merge_rescan_table(self._accepted(), fresh, changed_column_names=set())
        assert merged.business_metadata.generated_fields == ["description", "synonyms"]
        assert merged.columns[0].business_metadata.generated_fields == ["description", "tags"]

    def test_description_replaced_from_source_drops_its_marker(self) -> None:
        source_comment = BusinessMetadata(description="Order ID", enrichment_source=EnrichmentSource.DETERMINISTIC)
        fresh = Table(
            name="orders",
            database="sales",
            business_metadata=BusinessMetadata(description="Orders", enrichment_source=EnrichmentSource.DETERMINISTIC),
            columns=[Column(name="order_id", data_type="bigint", business_metadata=source_comment)],
        )
        merged = merge_rescan_table(self._accepted(), fresh, changed_column_names={"order_id"})
        assert merged.business_metadata.description == "Orders"
        assert merged.business_metadata.generated_fields == ["synonyms"]
        assert merged.columns[0].business_metadata.description == "Order ID"
        assert merged.columns[0].business_metadata.generated_fields == ["tags"]

    def test_added_column_carries_no_markers(self) -> None:
        fresh = Table(
            name="orders",
            database="sales",
            columns=[Column(name="order_id", data_type="bigint"), Column(name="型番", data_type="string")],
        )
        merged = merge_rescan_table(self._accepted(), fresh, changed_column_names=set())
        assert merged.columns[1].business_metadata.generated_fields == []


# ── Persistence ───────────────────────────────────────────────────────


class TestPersistence:
    def test_column_markers_round_trip_through_the_catalog_form(self) -> None:
        table = _table()
        table.columns[0].business_metadata.generated_fields = ["description", "tags"]
        restored = deserialize_form(serialize_form(table))
        assert restored.columns[0].business_metadata.generated_fields == ["description", "tags"]

    def test_legacy_column_without_the_set_proves_nothing(self) -> None:
        payload = serialize_form(_table())
        columns = json.loads(payload["columns"])
        for column in columns:
            column["business_metadata"].pop("generated_fields")
        payload["columns"] = json.dumps(columns)
        restored = deserialize_form(payload)
        assert all(c.business_metadata.generated_fields == [] for c in restored.columns)

    def test_table_markers_round_trip_as_a_json_list_member(self) -> None:
        table = _table(description="生成", tags=["取引"], generated_fields=["description", "tags"])
        payload = serialize_form(table)
        assert payload["generatedFields"] == '["description", "tags"]'
        assert deserialize_form(payload).business_metadata.generated_fields == ["description", "tags"]

    def test_table_without_markers_omits_the_member(self) -> None:
        # English and legacy tables keep the content they had before the member existed.
        assert "generatedFields" not in serialize_form(_table())

    def test_legacy_table_without_the_member_proves_nothing(self) -> None:
        payload = serialize_form(_table(description="生成", generated_fields=["description"]))
        del payload["generatedFields"]
        assert deserialize_form(payload).business_metadata.generated_fields == []

    def test_malformed_or_unknown_markers_read_as_absent(self) -> None:
        payload = serialize_form(_table())
        payload["generatedFields"] = "not json"
        assert deserialize_form(payload).business_metadata.generated_fields == []
        payload["generatedFields"] = '["description", "readme", 3]'
        assert deserialize_form(payload).business_metadata.generated_fields == ["description"]
