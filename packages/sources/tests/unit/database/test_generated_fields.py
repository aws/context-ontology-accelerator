"""Namespace language in database enrichment, and the ``generated_fields`` lifecycle.

A field is marked generated only when every value it holds was generated by
COA. Enrichment adds markers for what it generates in full; a steward edit or a
re-scan that replaces the value removes them; a value carried over unchanged
keeps its marker; legacy metadata carries none.
"""

from __future__ import annotations

import json
from unittest.mock import MagicMock, patch

# sources_handler first: database_routes is only importable through it.
import coa_sources.api.sources_handler  # noqa: F401, I001
