/**
 * Package the raw `packages/mcp-proxy` TypeScript source into a downloadable
 * zip, served from the web app so users who do NOT have repo access can still
 * obtain the MCP proxy from the MCP page.
 *
 * Why raw source (not compiled `dist/`): the proxy authenticates as the user
 * (Cognito PKCE browser login) and runs with their AWS credentials, so what we
 * hand out must be auditable before it is trusted. Shipping readable `src/`
 * (plus the files needed to build it) lets a user — or their security reviewer
 * — read exactly what it does. A minified `dist` blob would be an opaque
 * artifact the recipient cannot verify. The user builds it themselves with
 * `npm install && npx tsc --outDir dist`.
 *
 * What goes in the bundle: ONLY the source-of-truth files —
 *   src/, package.json, tsconfig.json, README.md
 * Excluded: node_modules/ (regenerated by `npm install`; machine-specific and
 * a supply-chain smell to redistribute), dist/ and coverage/ (generated).
 * `tests/` is included for auditability (a reviewer can see the auth flow is
 * tested) but is not required to run the proxy.
 *
 * Security properties (builder-security skill):
 *   - No secrets: the proxy stores no credential; it discovers everything from
 *     SSM and does browser PKCE. The bundle carries no .env / token / secret.
 *   - Integrity: a SHA-256 is emitted next to the zip so a tampered download is
 *     detectable. The MCP page shows it for the user to verify.
 *   - Served through the app's own auth-gated CloudFront (private S3 + OAC +
 *     Lambda@Edge authorizer) — NOT a new public download of executable code.
 *
 * Determinism: a fixed mtime and sorted file list keep the zip byte-stable
 * across rebuilds (so the SHA only changes when the source actually changes),
 * which also makes the CDK asset hash stable.
 *
 * Portability: the archive is written with Node's built-in `zlib` (a minimal
 * ZIP writer below) — NO external `zip`/`find`/`touch` binaries. CI runners do
 * not ship a `zip` binary, so shelling out crashed the web-app build (and every
 * job depending on it). Pure Node runs identically in CI and locally.
 *
 * This runs as the web-app `prebuild` step, so `npm run build` always
 * regenerates the zip from current source — the committed repo never carries a
 * stale binary (the output is gitignored).
 */
import { createHash } from "node:crypto";
import {
  mkdirSync,
  rmSync,
  readFileSync,
  writeFileSync,
  existsSync,
  readdirSync,
  statSync,
} from "node:fs";
import { dirname, join, resolve, posix } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateRawSync } from "node:zlib";

const here = dirname(fileURLToPath(import.meta.url));
const webAppRoot = resolve(here, "..");
const proxyRoot = resolve(webAppRoot, "..", "mcp-proxy");
const outDir = join(webAppRoot, "public", "downloads");
const zipName = "coa-mcp-proxy-src.zip";
const zipPath = join(outDir, zipName);
const shaPath = `${zipPath}.sha256`;

// Only the source-of-truth files. node_modules/dist/coverage are never copied.
const INCLUDE = ["src", "tests", "package.json", "tsconfig.json", "README.md"];
// Files/dirs never included even if nested under an INCLUDE entry.
const EXCLUDE_RE = /(^|[/\\])(node_modules|dist|coverage|\.turbo)([/\\]|$)/;
// A fixed DOS timestamp makes the archive reproducible (zip stores mtimes).
// 1980-01-01 00:00:00 is the ZIP epoch (date=0x0021, time=0x0000).
const DOS_TIME = 0x0000;
const DOS_DATE = 0x0021;

function fail(msg) {
  console.error(`[pack-mcp-proxy] ${msg}`);
  process.exit(1);
}

if (!existsSync(proxyRoot)) {
  fail(`mcp-proxy package not found at ${proxyRoot}`);
}

/** Recursively collect files under `root`, returning posix-relative paths. */
function walk(absRoot, relBase, acc) {
  for (const name of readdirSync(absRoot).sort()) {
    const abs = join(absRoot, name);
    const rel = posix.join(relBase, name);
    if (EXCLUDE_RE.test(rel)) continue;
    const st = statSync(abs);
    if (st.isDirectory()) {
      walk(abs, rel, acc);
    } else if (st.isFile()) {
      acc.push({ abs, rel });
    }
  }
  return acc;
}

// Gather all files, prefixed under a top-level `coa-mcp-proxy/` folder so the
// archive extracts to a single named directory. Sorted for stable entry order.
const files = [];
for (const entry of INCLUDE) {
  const src = join(proxyRoot, entry);
  if (!existsSync(src)) {
    if (entry === "tests") continue; // tests is optional
    fail(`required file missing from mcp-proxy: ${entry}`);
  }
  const st = statSync(src);
  if (st.isDirectory()) {
    walk(src, posix.join("coa-mcp-proxy", entry), files);
  } else {
    files.push({ abs: src, rel: posix.join("coa-mcp-proxy", entry) });
  }
}
files.sort((a, b) => (a.rel < b.rel ? -1 : a.rel > b.rel ? 1 : 0));

// ---- Minimal deterministic ZIP writer (store or deflate per entry) ----------
// CRC-32 (IEEE 802.3) table.
const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) {
      c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    }
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) {
    c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  }
  return (c ^ 0xffffffff) >>> 0;
}

const localParts = [];
const centralParts = [];
let offset = 0;

for (const f of files) {
  const nameBuf = Buffer.from(f.rel, "utf8");
  const data = readFileSync(f.abs);
  const crc = crc32(data);
  const deflated = deflateRawSync(data, { level: 9 });
  // Use deflate only when it actually helps; otherwise store (method 0).
  const useDeflate = deflated.length < data.length;
  const method = useDeflate ? 8 : 0;
  const body = useDeflate ? deflated : data;

  // Local file header (signature 0x04034b50).
  const local = Buffer.alloc(30);
  local.writeUInt32LE(0x04034b50, 0);
  local.writeUInt16LE(20, 4); // version needed
  local.writeUInt16LE(0, 6); // flags
  local.writeUInt16LE(method, 8);
  local.writeUInt16LE(DOS_TIME, 10);
  local.writeUInt16LE(DOS_DATE, 12);
  local.writeUInt32LE(crc, 14);
  local.writeUInt32LE(body.length, 18); // compressed size
  local.writeUInt32LE(data.length, 22); // uncompressed size
  local.writeUInt16LE(nameBuf.length, 26);
  local.writeUInt16LE(0, 28); // extra len
  localParts.push(local, nameBuf, body);

  // Central directory header (signature 0x02014b50).
  const central = Buffer.alloc(46);
  central.writeUInt32LE(0x02014b50, 0);
  central.writeUInt16LE(20, 4); // version made by
  central.writeUInt16LE(20, 6); // version needed
  central.writeUInt16LE(0, 8); // flags
  central.writeUInt16LE(method, 10);
  central.writeUInt16LE(DOS_TIME, 12);
  central.writeUInt16LE(DOS_DATE, 14);
  central.writeUInt32LE(crc, 16);
  central.writeUInt32LE(body.length, 20);
  central.writeUInt32LE(data.length, 24);
  central.writeUInt16LE(nameBuf.length, 28);
  central.writeUInt16LE(0, 30); // extra len
  central.writeUInt16LE(0, 32); // comment len
  central.writeUInt16LE(0, 34); // disk number
  central.writeUInt16LE(0, 36); // internal attrs
  central.writeUInt32LE(0, 38); // external attrs
  central.writeUInt32LE(offset, 42); // local header offset
  centralParts.push(central, nameBuf);

  offset += local.length + nameBuf.length + body.length;
}

const centralDir = Buffer.concat(centralParts);
const centralSize = centralDir.length;
const centralOffset = offset;

// End of central directory record (signature 0x06054b50).
const eocd = Buffer.alloc(22);
eocd.writeUInt32LE(0x06054b50, 0);
eocd.writeUInt16LE(0, 4); // disk number
eocd.writeUInt16LE(0, 6); // disk with central dir
eocd.writeUInt16LE(files.length, 8); // entries on this disk
eocd.writeUInt16LE(files.length, 10); // total entries
eocd.writeUInt32LE(centralSize, 12);
eocd.writeUInt32LE(centralOffset, 16);
eocd.writeUInt16LE(0, 20); // comment len

const zipBuf = Buffer.concat([...localParts, centralDir, eocd]);

mkdirSync(outDir, { recursive: true });
rmSync(zipPath, { force: true });
writeFileSync(zipPath, zipBuf);

const sha = createHash("sha256").update(zipBuf).digest("hex");
writeFileSync(shaPath, `${sha}  ${zipName}\n`);

const kb = (zipBuf.length / 1024).toFixed(1);
console.log(
  `[pack-mcp-proxy] wrote ${zipName} (${kb} KB, ${files.length} files)\n[pack-mcp-proxy] sha256 ${sha}`,
);
