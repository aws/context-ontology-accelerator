/**
 * Package the raw `packages/mcp-proxy` TypeScript source into a downloadable
 * zip, served from the web app so users who do NOT have repo access can still
 * obtain the MCP proxy from the MCP page.
 *
 * Why raw source (not compiled `dist/`): the proxy authenticates as the user
 * (Cognito PKCE browser login) and runs with their AWS credentials, so what we
 * hand out must be auditable before it is trusted. Shipping readable `src/`
 * (plus the files needed to build it) lets a user — or their security reviewer
 * — read exactly what it does. A minified `dist` blob would be an opaque
 * artifact the recipient cannot verify. The user builds it themselves with
 * `npm install && npm run build` (the command the MCP page shows).
 *
 * What goes in the bundle: ONLY the source-of-truth files —
 *   src/, tests/, tsconfig.json, README.md, and a build-only package.json
 * Excluded: node_modules/ (regenerated by `npm install`; machine-specific and
 * a supply-chain smell to redistribute), dist/ and coverage/ (generated).
 * `tests/` is included for auditability (a reviewer can see the auth flow is
 * tested) but is not required to build or run the proxy.
 *
 * Build-only package.json: the bundled `package.json` is GENERATED from
 * `packages/mcp-proxy/package.json` at pack time, keeping its name, version,
 * runtime `dependencies` and the `build`/`start` scripts, but only the dev
 * dependencies the build needs (`typescript`, `@types/node`). The test
 * toolchain (vitest, coverage) is left out on purpose: the package lives in a
 * pnpm workspace and has no npm lockfile, so `npm install` resolves the dev
 * tree against the registry of the day, and with vitest in it npm 10 (the npm
 * that ships with Node 22, the repo's minimum supported Node) crashes while
 * resolving vite's optional peer chain back to the newest vitest major.
 * Generating the file from the source package.json means it can never drift
 * from it: a version bump or a new runtime dependency flows into the zip on the
 * next build. `npm run build` (not `npx tsc`) also means a failed install stops
 * with "tsc: not found" instead of npx downloading the unrelated `tsc` package.
 *
 * Pinned direct dependencies: each bundled dependency and build dev dependency
 * is pinned to the exact version pnpm resolved for `packages/mcp-proxy` in the
 * repo's `pnpm-lock.yaml` (the versions the repo builds and tests with), read
 * at pack time with no network access. Packing fails if the lockfile entry is
 * missing or its specifier no longer matches package.json, so a stale lockfile
 * cannot ship. Only the DIRECT dependencies are pinned: npm still resolves
 * their own dependencies from the registry when the user runs `npm install`.
 * A generated npm lockfile would pin those too, but producing one needs the
 * registry during the web build, and a committed one has nothing in this pnpm
 * repo to keep it current.
 *
 * Security properties (builder-security skill):
 *   - No secrets: the proxy stores no credential; it discovers everything from
 *     SSM and does browser PKCE. The bundle carries no .env / token / secret.
 *   - Integrity: a SHA-256 is emitted next to the zip so a corrupted or
 *     partial download is detectable; the MCP page shows it for the user to
 *     check. It covers the zip, which holds the source and the pinned direct
 *     dependency versions, not the packages `npm install` fetches. The digest
 *     is served from the same origin as the zip (and as the page's own JS), so
 *     it is not evidence of who published the zip.
 *   - Served as a static file of the console's CloudFront distribution (private
 *     S3 + OAC). The console's sign-in runs in the browser and does not gate
 *     static files, so the zip and its `.sha256` download WITHOUT signing in
 *     unless the deployment sets the optional Lambda@Edge authorizer
 *     (`edge_auth_version_arn`). That is acceptable because the bundle is
 *     source code only, with no secrets and no deployment-specific values.
 *
 * Determinism: a fixed mtime, a sorted file list and a generated package.json
 * with a fixed key order keep the zip byte-stable across rebuilds (so the SHA
 * only changes when the source actually changes), which also makes the CDK
 * asset hash stable.
 *
 * Portability: the archive is written with Node's built-in `zlib` (a minimal
 * ZIP writer below) — NO external `zip`/`find`/`touch` binaries. CI runners do
 * not ship a `zip` binary, so shelling out crashed the web-app build (and every
 * job depending on it). Pure Node runs identically in CI and locally.
 *
 * This runs as the web-app `prebuild` step, so `npm run build` always
 * regenerates the zip from current source — the committed repo never carries a
 * stale binary (the output is gitignored). `packMcpProxy` and the helpers the
 * web-app tests check are exported so the tests need not write into `public/`.
 */
import { createHash } from "node:crypto";
import {
  mkdirSync,
  rmSync,
  readFileSync,
  realpathSync,
  writeFileSync,
  existsSync,
  readdirSync,
  statSync,
} from "node:fs";
import { dirname, join, resolve, posix } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateRawSync } from "node:zlib";

const here = dirname(fileURLToPath(import.meta.url));
const webAppRoot = resolve(here, "..");
export const DEFAULT_PROXY_ROOT = resolve(webAppRoot, "..", "mcp-proxy");
/** The workspace lockfile the bundled dependency versions are pinned from. */
export const DEFAULT_LOCKFILE = resolve(
  webAppRoot,
  "..",
  "..",
  "pnpm-lock.yaml",
);
/** The proxy's key under `importers:` in pnpm-lock.yaml. */
const LOCK_IMPORTER = "packages/mcp-proxy";
const DEFAULT_OUT_DIR = join(webAppRoot, "public", "downloads");
export const ZIP_NAME = "coa-mcp-proxy-src.zip";
/** Top-level folder every entry extracts into. */
const BUNDLE_DIR = "coa-mcp-proxy";

// Only the source-of-truth files. node_modules/dist/coverage are never copied.
// package.json is not copied verbatim: see buildBundlePackageJson().
const INCLUDE = ["src", "tests", "package.json", "tsconfig.json", "README.md"];
// Files/dirs never included even if nested under an INCLUDE entry.
const EXCLUDE_RE = /(^|[/\\])(node_modules|dist|coverage|\.turbo)([/\\]|$)/;
// A fixed DOS timestamp makes the archive reproducible (zip stores mtimes).
// 1980-01-01 00:00:00 is the ZIP epoch (date=0x0021, time=0x0000).
const DOS_TIME = 0x0000;
const DOS_DATE = 0x0021;

/** Top-level package.json fields carried into the bundle, in this order. */
const PACKAGE_FIELDS = [
  "name",
  "version",
  "description",
  "private",
  "type",
  "license",
  "engines",
];
/** Scripts that work with the bundled dependencies (`test` needs vitest). */
export const BUNDLE_SCRIPTS = ["build", "start"];
/** The only dev dependencies the build needs: the compiler and Node types. */
export const BUILD_DEV_DEPENDENCIES = ["@types/node", "typescript"];

/** An exact registry version (`1.2.3`, `1.2.3-rc.1`), not a range or link. */
const EXACT_VERSION_RE =
  /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/;

function pick(obj, keys) {
  const out = {};
  for (const key of keys) {
    if (Object.hasOwn(obj, key)) out[key] = obj[key];
  }
  return out;
}

/** A YAML scalar as pnpm writes it: plain, 'single-quoted' or "double-quoted". */
function unquote(value) {
  if (value.length >= 2 && value.startsWith("'") && value.endsWith("'")) {
    return value.slice(1, -1).replaceAll("''", "'");
  }
  if (value.length >= 2 && value.startsWith('"') && value.endsWith('"')) {
    return JSON.parse(value);
  }
  return value;
}

/**
 * The `specifier` and `version` pnpm recorded for one workspace package's
 * direct dependencies, read from the `importers:` section of a pnpm-lock.yaml
 * (lockfile v9 layout). Returns `{ dependencies: { name: { specifier,
 * version } }, devDependencies: {...}, ... }`. A line reader for that one
 * section keeps the web build free of a YAML dependency.
 */
export function readLockedVersions(lockText, importer = LOCK_IMPORTER) {
  const lines = lockText.split(/\r?\n/);
  const top = lines.indexOf("importers:");
  if (top < 0) throw new Error("pnpm-lock.yaml has no importers section");
  const header = `  ${importer}:`;
  let i = lines.indexOf(header, top + 1);
  if (i < 0) throw new Error(`pnpm-lock.yaml has no importer ${importer}`);
  const out = {};
  let field = null;
  let name = null;
  for (i += 1; i < lines.length; i++) {
    const line = lines[i];
    if (line.trim() === "") continue;
    const indent = line.length - line.trimStart().length;
    if (indent <= 2) break; // the next importer or top-level section
    const m = /^\s*('[^']*(?:''[^']*)*'|"[^"]*"|[^:]+):(?:\s+(.*))?$/.exec(
      line,
    );
    if (!m) continue;
    const key = unquote(m[1]);
    const value = m[2] === undefined ? undefined : unquote(m[2].trim());
    if (indent === 4) {
      field = key;
      out[field] = {};
      name = null;
    } else if (indent === 6 && field) {
      name = key;
      out[field][name] = {};
    } else if (indent === 8 && field && name && value !== undefined) {
      out[field][name][key] = value;
    }
  }
  return out;
}

/** `deps` with each range replaced by the exact version pnpm locked for it. */
function pinToLockfile(deps, locked, field) {
  const out = {};
  for (const [name, range] of Object.entries(deps)) {
    const entry = locked[field]?.[name];
    if (!entry?.version) {
      throw new Error(
        `pnpm-lock.yaml has no ${field} entry for ${name} in ${LOCK_IMPORTER}; run pnpm install`,
      );
    }
    if (entry.specifier !== range) {
      throw new Error(
        `pnpm-lock.yaml is out of date for ${name}: package.json has ${range}, the lockfile ${entry.specifier}; run pnpm install`,
      );
    }
    // pnpm appends the resolved peers in parentheses: "4.1.12(vitest@4.1.12)".
    const version = entry.version.split("(")[0];
    if (!EXACT_VERSION_RE.test(version)) {
      throw new Error(
        `cannot pin ${name}: its locked version ${entry.version} is not a registry version`,
      );
    }
    out[name] = version;
  }
  return out;
}

/**
 * The build-only package.json shipped in the zip, derived from the proxy's own
 * package.json, with every dependency pinned to the exact version in `locked`
 * (from readLockedVersions). Throws if the source no longer has what the
 * documented build (`npm install && npm run build`) relies on, or if the
 * lockfile does not match the source package.json.
 */
export function buildBundlePackageJson(sourcePkg, locked) {
  if (!sourcePkg?.scripts?.build) {
    throw new Error("mcp-proxy package.json has no `build` script");
  }
  for (const dep of BUILD_DEV_DEPENDENCIES) {
    if (!sourcePkg.devDependencies?.[dep]) {
      throw new Error(`mcp-proxy package.json devDependencies has no ${dep}`);
    }
  }
  return {
    ...pick(sourcePkg, PACKAGE_FIELDS),
    scripts: pick(sourcePkg.scripts, BUNDLE_SCRIPTS),
    dependencies: pinToLockfile(
      sourcePkg.dependencies ?? {},
      locked,
      "dependencies",
    ),
    devDependencies: pinToLockfile(
      pick(sourcePkg.devDependencies, BUILD_DEV_DEPENDENCIES),
      locked,
      "devDependencies",
    ),
  };
}

/** Read and parse a JSON file, naming the file if it does not parse. */
function readJson(path) {
  const text = readFileSync(path, "utf8");
  try {
    return JSON.parse(text);
  } catch (err) {
    throw new Error(`cannot parse ${path}: ${err.message}`, { cause: err });
  }
}

/** Recursively collect files under `root`, returning posix-relative paths. */
function walk(absRoot, relBase, acc) {
  for (const name of readdirSync(absRoot).sort()) {
    const abs = join(absRoot, name);
    const rel = posix.join(relBase, name);
    if (EXCLUDE_RE.test(rel)) continue;
    const st = statSync(abs);
    if (st.isDirectory()) {
      walk(abs, rel, acc);
    } else if (st.isFile()) {
      acc.push({ rel, data: readFileSync(abs) });
    }
  }
  return acc;
}

/**
 * Every bundle entry as `{ rel, data }`, prefixed under `coa-mcp-proxy/` so the
 * archive extracts to a single named directory. Sorted for stable entry order.
 */
function collectBundleEntries(proxyRoot, lockfile) {
  if (!existsSync(proxyRoot)) {
    throw new Error(`mcp-proxy package not found at ${proxyRoot}`);
  }
  if (!existsSync(lockfile)) {
    throw new Error(`pnpm-lock.yaml not found at ${lockfile}`);
  }
  const locked = readLockedVersions(readFileSync(lockfile, "utf8"));
  const files = [];
  for (const entry of INCLUDE) {
    const src = join(proxyRoot, entry);
    if (!existsSync(src)) {
      if (entry === "tests") continue; // tests is optional
      throw new Error(`required file missing from mcp-proxy: ${entry}`);
    }
    const rel = posix.join(BUNDLE_DIR, entry);
    if (entry === "package.json") {
      const pkg = buildBundlePackageJson(readJson(src), locked);
      files.push({
        rel,
        data: Buffer.from(`${JSON.stringify(pkg, null, 2)}\n`, "utf8"),
      });
    } else if (statSync(src).isDirectory()) {
      walk(src, rel, files);
    } else {
      files.push({ rel, data: readFileSync(src) });
    }
  }
  return files.sort((a, b) => (a.rel < b.rel ? -1 : a.rel > b.rel ? 1 : 0));
}

// ---- Minimal deterministic ZIP writer (store or deflate per entry) ----------
// CRC-32 (IEEE 802.3) table.
const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) {
      c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    }
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) {
    c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  }
  return (c ^ 0xffffffff) >>> 0;
}

/** A deterministic ZIP archive of `entries` (store or deflate per entry). */
function buildZip(entries) {
  const localParts = [];
  const centralParts = [];
  let offset = 0;

  for (const { rel, data } of entries) {
    const nameBuf = Buffer.from(rel, "utf8");
    const crc = crc32(data);
    const deflated = deflateRawSync(data, { level: 9 });
    // Use deflate only when it actually helps; otherwise store (method 0).
    const useDeflate = deflated.length < data.length;
    const method = useDeflate ? 8 : 0;
    const body = useDeflate ? deflated : data;

    // Local file header (signature 0x04034b50).
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4); // version needed
    local.writeUInt16LE(0, 6); // flags
    local.writeUInt16LE(method, 8);
    local.writeUInt16LE(DOS_TIME, 10);
    local.writeUInt16LE(DOS_DATE, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(body.length, 18); // compressed size
    local.writeUInt32LE(data.length, 22); // uncompressed size
    local.writeUInt16LE(nameBuf.length, 26);
    local.writeUInt16LE(0, 28); // extra len
    localParts.push(local, nameBuf, body);

    // Central directory header (signature 0x02014b50).
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4); // version made by
    central.writeUInt16LE(20, 6); // version needed
    central.writeUInt16LE(0, 8); // flags
    central.writeUInt16LE(method, 10);
    central.writeUInt16LE(DOS_TIME, 12);
    central.writeUInt16LE(DOS_DATE, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(body.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBuf.length, 28);
    central.writeUInt16LE(0, 30); // extra len
    central.writeUInt16LE(0, 32); // comment len
    central.writeUInt16LE(0, 34); // disk number
    central.writeUInt16LE(0, 36); // internal attrs
    central.writeUInt32LE(0, 38); // external attrs
    central.writeUInt32LE(offset, 42); // local header offset
    centralParts.push(central, nameBuf);

    offset += local.length + nameBuf.length + body.length;
  }

  const centralDir = Buffer.concat(centralParts);

  // End of central directory record (signature 0x06054b50).
  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(0x06054b50, 0);
  eocd.writeUInt16LE(0, 4); // disk number
  eocd.writeUInt16LE(0, 6); // disk with central dir
  eocd.writeUInt16LE(entries.length, 8); // entries on this disk
  eocd.writeUInt16LE(entries.length, 10); // total entries
  eocd.writeUInt32LE(centralDir.length, 12);
  eocd.writeUInt32LE(offset, 16); // central directory offset
  eocd.writeUInt16LE(0, 20); // comment len

  return Buffer.concat([...localParts, centralDir, eocd]);
}

/**
 * Write the zip and its `.sha256` sidecar into `outDir`. Returns the digest,
 * the archive and its entry count so callers (and tests) can inspect it.
 */
export function packMcpProxy({
  proxyRoot = DEFAULT_PROXY_ROOT,
  outDir = DEFAULT_OUT_DIR,
  lockfile = DEFAULT_LOCKFILE,
} = {}) {
  const entries = collectBundleEntries(proxyRoot, lockfile);
  const zipBuf = buildZip(entries);
  const zipPath = join(outDir, ZIP_NAME);
  const shaPath = `${zipPath}.sha256`;

  mkdirSync(outDir, { recursive: true });
  rmSync(zipPath, { force: true });
  writeFileSync(zipPath, zipBuf);

  const sha = createHash("sha256").update(zipBuf).digest("hex");
  writeFileSync(shaPath, `${sha}  ${ZIP_NAME}\n`);
  return { sha, zipBuf, fileCount: entries.length };
}

/**
 * Whether the script at `argv1` is the module at `moduleUrl`. Compares real
 * paths: Node gives the main module its real path in `import.meta.url`, so a
 * plain path comparison is false when the checkout is reached through a
 * symlink, and the prebuild would then exit 0 without writing the zip.
 */
export function isMainModule(argv1, moduleUrl) {
  if (!argv1) return false;
  try {
    return realpathSync(argv1) === realpathSync(fileURLToPath(moduleUrl));
  } catch {
    return false;
  }
}

// Run only when invoked as a script (`node scripts/pack-mcp-proxy.mjs`), not
// when a test imports the module.
if (isMainModule(process.argv[1], import.meta.url)) {
  try {
    const { zipBuf, sha, fileCount } = packMcpProxy();
    const kb = (zipBuf.length / 1024).toFixed(1);
    console.log(
      `[pack-mcp-proxy] wrote ${ZIP_NAME} (${kb} KB, ${fileCount} files)\n[pack-mcp-proxy] sha256 ${sha}`,
    );
  } catch (err) {
    console.error(
      `[pack-mcp-proxy] ${err instanceof Error ? err.message : String(err)}`,
    );
    process.exit(1);
  }
}
