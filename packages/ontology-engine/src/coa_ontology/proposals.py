"""Ontology proposals API.

Proposals are generated by ``/induce`` and stored in DynamoDB. Users can
list, view, accept, reject, cancel, validate, or update them.

Accept is **asynchronous**: ``POST /accept`` flips the proposal's status
to ``accepting``, kicks off the shared ingest pipeline in
:mod:`coa_ontology.catalog.ingest` on a background thread,
and returns 202 immediately. Clients poll the existing
``GET /proposals/{id}`` endpoint and watch the ``status`` field flip to
``accepted`` (success) or ``accept_failed`` with ``accept_error`` naming
the pipeline step that failed. An ``accept_failed`` proposal is
re-acceptable: re-running converges on a correct graph (triples dedup,
counts are reconciled from Neptune), with the known non-idempotent
residual documented at the ``ingest`` step. It converges but does NOT
resume — every re-accept restarts at ``ingest`` (#851). The work itself
can take 30–60 seconds (catalog projection,
Turtle bulk load, embedding accumulation, S3 persist), which exceeds
API Gateway's 29-second integration timeout, so we must run it
asynchronously.
"""

