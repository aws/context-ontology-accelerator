class ValidateProposalRequest(BaseModel):
    """Request body for validating a proposal across the selected tiers."""

    tiers: list[str] = ["tier1_blocking", "tier2_scoring", "tier3_review"]
    shacl_shapes_turtle: str | None = None
    competency_questions: list[str] | None = None


_MAX_VALIDATION_JOBS = 200
_validation_jobs: dict[str, dict] = {}

# Statuses past which a job never changes (mirrors dynamo_store).
_TERMINAL_STATUSES = frozenset({"completed", "failed", "cancelled"})


def _persist_async_job(kind: str, job: dict, namespace: str) -> None:
    """Best-effort write of a job's current state to DynamoDB.

    The in-memory dict is a fast-path cache; DynamoDB is the durable copy that
    survives ECS task restarts and cross-instance polls. Uses an unconditional
    put (upsert) — ``job`` always holds the full current state, so we don't need
    a read-before-write to choose insert-vs-update (that was an extra round-trip
    on every status transition). Persisted under the proposal's ``namespace`` so
    the async-job partition stays tenant-isolated, matching the proposal row.
    Persistence failures are logged and swallowed — the poll can still read the
    in-memory copy on the same task.
    """
    try:
        dynamo_store.put_async_job(kind, job["job_id"], job, namespace=namespace)
    except Exception:  # noqa: BLE001 — durability is best-effort
        _log.warning("Failed to persist %s job %s to DynamoDB", kind, job.get("job_id"), exc_info=True)


def _safe_get_async_job(kind: str, job_id: str, namespace: str) -> dict | None:
    """Read the durable job copy, tolerating an unreachable DynamoDB.

    The poll's in-memory miss falls back here; if DynamoDB is unavailable we
    return None (→ caller raises a clean 404) rather than surfacing a 500. This
    keeps the not-found path working even when the durable store can't be read.
    """
    try:
        return dynamo_store.get_async_job(kind, job_id, namespace=namespace)
    except Exception:  # noqa: BLE001 — fall through to 404 on any store error
        _log.warning("Failed to read %s job %s from DynamoDB", kind, job_id, exc_info=True)
        return None


def _evict_terminal_jobs(jobs: dict[str, dict], cap: int) -> None:
    """Bound the in-memory job dict, preferring to evict TERMINAL jobs.

    The in-memory dict is only a fast-path cache — every job is also persisted
    to DynamoDB, and the poll falls back to that durable copy on a cache miss.
    So we evict oldest TERMINAL jobs first (their poll reads the finished DDB
    row); if that alone can't get under the cap because everything is still
    running, we force-evict the oldest entries anyway at a hard ceiling. The
    running job's poll still resolves via the DynamoDB fallback, so eviction
    never loses a result — it just falls back to the durable store. Without the
    hard ceiling the dict could grow unbounded when all jobs are non-terminal.
    Insertion order = age (dict preserves it).
    """
    if len(jobs) < cap:
        return
    # First pass: drop oldest terminal jobs.
    for jid in list(jobs.keys()):
        if len(jobs) < cap:
            return
        if str(jobs[jid].get("status")) in _TERMINAL_STATUSES:
            del jobs[jid]
    # Hard ceiling: if still over cap (all non-terminal), force-evict oldest.
    # Their status lives in DynamoDB, so the poll still resolves via fallback.
    for jid in list(jobs.keys()):
        if len(jobs) < cap:
            break
        del jobs[jid]


def _run_proposal_validation(
    job_id: str,
    turtle: str,
    body: ValidateProposalRequest,
    proposal_id: str,
    namespace: str,
    r2rml_turtle: str | None = None,
):
    from coa_ontology.validation.schemas import (
        ValidationTier,
    )
    from coa_ontology.validation.validators import OntologyValidator
    from coa_ontology.validation.validators.tier1 import (
        ConnectivityValidator,
        ConsistencyValidator,
        DatatypeTokenValidator,
        SHACLValidator,
        TaxonomyCycleValidator,
    )
    from coa_ontology.validation.validators.tier2 import StructuralMetricsValidator
    from coa_ontology.validation.validators.tier3 import (
        AmbiguousMatchValidator,
        CompetencyQuestionValidator,
        LabelCompletenessValidator,
        OoPSValidator,
    )

    validators_by_tier: dict[ValidationTier, list[OntologyValidator]] = {
        ValidationTier.tier1_blocking: [
            ConsistencyValidator(),
            TaxonomyCycleValidator(),
            ConnectivityValidator(),
            SHACLValidator(),
            DatatypeTokenValidator(),
        ],
        ValidationTier.tier2_scoring: [
            StructuralMetricsValidator(),
        ],
        ValidationTier.tier3_review: [
            OoPSValidator(),
            LabelCompletenessValidator(),
            AmbiguousMatchValidator(),
            CompetencyQuestionValidator(),
        ],
    }

    job = _validation_jobs.get(job_id)
    if not job:
        return
    job["status"] = "running"
    _persist_async_job("VALIDATE", job, namespace)
    try:
        g = Graph()
        g.parse(data=turtle, format="turtle")

        all_findings = []
        metrics_out: dict = {}
        tiers = [ValidationTier(t) for t in body.tiers]

        for tier in tiers:
            for v in validators_by_tier.get(tier) or []:
                all_findings.extend(
                    v.validate(
                        g,
                        shacl_shapes_turtle=body.shacl_shapes_turtle,
                        competency_questions=body.competency_questions or [],
                        r2rml_turtle=r2rml_turtle,
                        _metrics_out=metrics_out,
                    )
                )

        passed = not any(f.severity == "error" for f in all_findings)

        job["status"] = "completed"
        job["report"] = {
            "job_id": job_id,
            "proposal_id": proposal_id,
            "passed": passed,
            "findings": [f.model_dump() for f in all_findings],
            "metrics": metrics_out if metrics_out else None,
            "tiers_run": body.tiers,
            "created_at": job["created_at"],
        }
        _persist_async_job("VALIDATE", job, namespace)
    except Exception as e:
        _log.error("Proposal validation failed for job %s: %s", job_id, e, exc_info=True)
        job["status"] = "failed"
        job["error"] = f"Validation failed: {type(e).__name__}"
        _persist_async_job("VALIDATE", job, namespace)


@router.post("/{proposal_id}/validate")
def validate_proposal(
    proposal_id: str,
    body: ValidateProposalRequest | None = None,
    namespace: str = "default",
):
    """Run multi-tier validation on a proposal's Turtle without accepting it.

    Returns a validation job that can be polled for results. This lets
    the UI show reasoner findings, structural metrics, and OoPS! pitfalls
    before the user decides to accept or reject.
    """
    item = dynamo_store.get_proposal_by_id(proposal_id, namespace=namespace)
    if not item:
        raise HTTPException(404, f"Proposal '{proposal_id}' not found")

    turtle = item.get("ontology_turtle", "")
    if not turtle:
        raise HTTPException(409, "Proposal has no ontology_turtle to validate")

    # R2RML too (inline or from S3) so the datatype validator can flag malformed
    # rr:datatype tokens — they reach Ontop via the accept-time range-alignment
    # step even when the ontology turtle itself is clean.
    r2rml_turtle = item.get("r2rml_turtle") or ""
    if not r2rml_turtle and item.get("r2rml_s3_key"):
        # Best-effort: validation still runs against the ontology turtle if this
        # fails. But log it — a silent failure here means the datatype validator
        # skips rr:datatype tokens (which reach Ontop via accept-time range
        # alignment), so a masked infra issue would silently defeat the feature.
        try:
            r2rml_turtle = dynamo_store._get_artifact_s3(namespace, proposal_id, "r2rml") or ""
        except Exception as e:
            _log.warning(
                "validate[%s]: failed to fetch R2RML from S3; datatype validator will skip rr:datatype (%s: %s)",
                proposal_id,
                type(e).__name__,
                e,
            )

    if body is None:
        body = ValidateProposalRequest()

    job_id = str(uuid.uuid4())

    # Evict oldest TERMINAL jobs only — never a running/pending one.
    _evict_terminal_jobs(_validation_jobs, _MAX_VALIDATION_JOBS)

    _validation_jobs[job_id] = {
        "job_id": job_id,
        "proposal_id": proposal_id,
        "status": "pending",
        "created_at": datetime.now(UTC).isoformat(),
        "report": None,
        "error": None,
    }
    _persist_async_job("VALIDATE", _validation_jobs[job_id], namespace)

    Thread(
        target=_run_proposal_validation,
        args=(job_id, turtle, body, proposal_id, namespace),
        kwargs={"r2rml_turtle": r2rml_turtle or None},
        daemon=True,
    ).start()
    return _validation_jobs[job_id]


@router.get("/{proposal_id}/validate/jobs/{job_id}")
def get_proposal_validation_job(proposal_id: str, job_id: str, namespace: str = "default"):
    """Poll a proposal validation job for results.

    Reads the in-memory copy first (fast path, same task) and falls back to the
    DynamoDB copy so the poll still resolves after a task restart / on a
    different instance (a stale non-terminal row is swept to ``failed``).
    """
    job = _validation_jobs.get(job_id)
    if not job:
        job = _safe_get_async_job("VALIDATE", job_id, namespace)
    if not job or job.get("proposal_id") != proposal_id:
        raise HTTPException(404, "Validation job not found")
    return job


