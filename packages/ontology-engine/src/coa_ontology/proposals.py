def _ontology_short_id(ontology_id: str) -> str:
    """Return the last meaningful segment of an ontology IRI.

    Used as the S3 filename stem and as the ``version`` in the
    ontology.published event. Shared by ``_persist_induced_to_s3`` and the
    ``notify_vkg`` accept step so the event's version always matches the object
    actually written.

    Args:
        ontology_id: The ontology IRI to shorten.

    Returns:
        The trailing segment, with IRI punctuation replaced by underscores.
    """
    safe_id = ontology_id.replace("/", "_").replace("#", "").replace(":", "_").rstrip("_")
    return safe_id.split("_")[-1] if "_" in safe_id else safe_id


def _mapping_table_names(r2rml_turtle: str | None) -> set[str] | None:
    """The ``rr:tableName`` literals the mapping being persisted actually declares.

    ``None`` means "unknown" — no mapping was supplied, or it did not parse — and
    the caller then falls back to deriving names from the catalog alone.

    Returns:
        The set of logical-table literals, or ``None`` when they cannot be read.
    """
    if not r2rml_turtle:
        return None
    from rdflib import Graph, Namespace

    rr = Namespace("http://www.w3.org/ns/r2rml#")
    try:
        graph = Graph().parse(data=r2rml_turtle, format="turtle")
    except Exception as e:  # noqa: BLE001 - degrade to catalog-derived names
        _log.warning(
            "schema.sql: could not parse the R2RML mapping to read its logical table names "
            "(%s); falling back to catalog-derived names, which may not match",
            type(e).__name__,
        )
        return None
    return {str(o) for o in graph.objects(None, rr.tableName)}


def _generate_schema_sql(
    namespace: str,
    ontology_id: str,
    r2rml_turtle: str | None = None,
    extra_datasource_ids: list[str] | None = None,
) -> str | None:
    """Generate H2 DDL from datasource catalog metadata.

    Returns the schema.sql text, or ``None`` when there is nothing to describe
    (no accepted datasources, or datasources that yield no catalog tables — e.g.
    an unstructured ontology). Identifiers are emitted verbatim (SQL-delimited)
    so they match the source datasource; no canonical→original column map is
    needed.

    ``r2rml_turtle`` is the mapping being persisted alongside this DDL. It is what
    makes the two agree: the logical-table names in a mapping depend on WHICH
    tables were in the run that produced it (a bare ``customers`` while one source
    exposed that name, ``"public__2f77729f"."customers"`` once two did), and the
    table set re-derived here is the union over ALL accepted proposals — a
    different set, so a re-derivation can name a table differently from the
    mapping that is about to be stored beside it. Ontop rejects a mapping naming a
    table its validation schema does not declare, and that failure is
    namespace-wide, not per-table. Passing the mapping makes the DDL a function of
    it (see :func:`_tables_to_h2_ddl`) instead of a parallel guess.

    ``extra_datasource_ids`` are unioned with the datasource ids gathered from the
    accepted-proposal scan. The scan (``list_proposals(status="accepted")``) is
    eventually consistent, and this can run inside the very accept that flipped its
    own proposal to ``accepted`` moments earlier — so on a merge the scan may not
    yet see it and would drop that source's tables. Passing the in-flight accept's
    own ids here closes that read-after-write gap; they union with, never replace,
    the scan, so re-accepts stay idempotent.

    Raises :class:`SchemaSqlGenerationError` on a genuine failure so the caller
    can tell it apart from the ``None`` empty state.
    """
    import os

    try:
        from coa_ontology.induce_catalog import _catalog_to_tables, _fetch_catalog_from_smus
        from coa_ontology.inducer.services.data_catalog import CatalogTable
        from coa_ontology.inducer.strategies.base import schema_from_fqn

        # Collect datasource IDs from accepted proposals for this ontology
        accepted = dynamo_store.list_proposals(
            namespace=namespace, ontology_id=ontology_id, status=ProposalStatus.ACCEPTED.value
        )
        ds_ids: set[str] = set()
        for p in accepted:
            meta = p.get("metadata") or {}
            for ds_id in meta.get("datasource_ids") or []:
                ds_ids.add(ds_id)

        # Union the CURRENT accept's datasource ids. ``list_proposals`` is an
        # eventually-consistent DynamoDB scan, and this runs inside the same accept
        # that just flipped its own proposal to ``accepted`` a few steps earlier —
        # so the scan can miss that proposal and drop its source's tables from the
        # DDL, even though the merged mapping (accumulated from Neptune) still names
        # them. That mismatch makes ``_tables_to_h2_ddl`` fail closed, leaving a
        # stale schema.sql and breaking every Tier-2 query in the namespace. Adding
        # the in-flight ids here closes the read-after-write gap deterministically;
        # they union with (never replace) the scan, so a re-accept is idempotent.
        for ds_id in extra_datasource_ids or []:
            ds_ids.add(ds_id)

        # Legitimate empty state: an ontology with no structured datasources
        # (e.g. unstructured) has no tables to describe. Not an error.
        if not ds_ids:
            return None

        # Fetch catalog tables for each datasource
        catalog_source = os.environ.get("CATALOG_SOURCE", "http")
        config = {
            "catalog_source": catalog_source,
            "data_catalog_url": os.environ.get("DATA_CATALOG_URL", ""),
            "smus_domain_id": os.environ.get("SMUS_DOMAIN_ID", ""),
            "namespaces_table": os.environ.get("NAMESPACES_TABLE", ""),
            "smus_datasources_table": os.environ.get("DATASOURCES_TABLE", ""),
            "sources_table": os.environ.get("SOURCES_TABLE", ""),
            "smus_region": os.environ.get("AWS_REGION", "us-east-1"),
        }

        all_tables: list[CatalogTable] = []
        for ds_id in ds_ids:
            if catalog_source == "smus":
                catalog = _fetch_catalog_from_smus(config, ds_id, namespace=namespace)
            else:
                from coa_ontology.induce_catalog import _fetch_catalog

                catalog = _fetch_catalog(config["data_catalog_url"], ds_id)
            for tbl_dict in _catalog_to_tables(catalog):
                # Stamp datasource identity exactly as the induction and
                # infer-constraints paths do (induce_catalog._run_induction,
                # _fetch_catalog_tables). Without it every table here shares a
                # datasourceId of None, so two sources' same-named tables collapse
                # to one identity and the H2 DDL disagrees with the mapping's
                # logical names — Ontop then rejects the mapping at VKG load.
                tbl_dict["datasourceId"] = ds_id
                # schema_from_fqn, not fqn.split(".")[0]: the schema is the segment
                # NEAREST the table, so a 3-part catalog.database.table would
                # otherwise stamp the CATALOG name here, and this value becomes
                # coa:sourceSchema — the schema serve puts in the executed SQL.
                tbl_dict["sourceSchema"] = schema_from_fqn(tbl_dict.get("fullyQualifiedName")) or None
                all_tables.append(CatalogTable(**tbl_dict))

        # Legitimate empty state: datasources resolved but exposed no tables.
        if not all_tables:
            return None

        return _tables_to_h2_ddl(all_tables, _mapping_table_names(r2rml_turtle))

    except Exception as e:
        # Genuine failure — do NOT mask as the ``None`` empty state (#457).
        raise SchemaSqlGenerationError(f"{type(e).__name__}: {e}") from e


# H2 type mapping from catalog types
_CATALOG_TO_H2 = {
    "INT": "INTEGER",
    "INTEGER": "INTEGER",
    "BIGINT": "INTEGER",
    "SMALLINT": "SMALLINT",
    "TINYINT": "TINYINT",
    "FLOAT": "FLOAT",
    "DOUBLE": "DOUBLE",
    "DECIMAL": "DECIMAL",
    "NUMERIC": "DECIMAL",
    "VARCHAR": "VARCHAR(255)",
    "TEXT": "VARCHAR(65535)",
    "CHAR": "CHAR(255)",
    "STRING": "VARCHAR(255)",
    "BOOLEAN": "BOOLEAN",
    # Temporal types map faithfully. These were previously VARCHAR(255), which
    # forced the R2RML rr:datatype and the ontology rdfs:range to xsd:string to
    # stay consistent with this schema. The consequence was that Ontop's type
    # reasoner saw every temporal column as a string, found comparisons against
    # xsd:date/xsd:dateTime literals disjoint, proved the query unsatisfiable,
    # and emitted its no-mapping placeholder ("SELECT 1 AS uselessVariable") —
    # so EVERY date-filtered SPARQL query returned nothing. Verified against
    # Ontop 5.5.0: faithful temporal types load cleanly (no
    # MappingOntologyMismatchException) and produce real SQL.
    "DATE": "DATE",
    "TIMESTAMP": "TIMESTAMP",
    "DATETIME": "TIMESTAMP",
    "TIME": "TIME",
    # UUID is textual; declared explicitly so it does not rely on the
    # VARCHAR fallback (which would hide a genuinely unmapped type).
    "UUID": "VARCHAR(36)",
    "BINARY": "VARBINARY",
    "BLOB": "BLOB",
}


def _align_to_mapping(
    logical_names: dict[str, str],
    tables: list,
    mapping_table_names: set[str] | None,
) -> dict[str, str]:
    """Replace each catalog-derived logical name with the one the MAPPING declares.

    :func:`logical_table_names` is set-dependent by design — a bare name is
    qualified only while another table in the same run shares it — so two callers
    working from different table sets legitimately disagree. The mapping wins,
    because Ontop validates the mapping against this schema and not the reverse; a
    name only this schema knows about describes a table nothing asks for, while a
    name only the mapping knows about fails VKG load for the whole namespace.

    Three candidates per table, most specific first: the derived name, the bare
    name (the mapping was accepted while this name was unique), and — for the
    reverse skew, where the mapping qualified a name this run does not have to —
    the mapping's own unique literal ending in this table's name.

    Args:
        logical_names: Identity -> catalog-derived ``rr:tableName`` literal.
        tables: Tables the DDL will describe.
        mapping_table_names: Literals the mapping declares, or ``None`` if unknown.

    Returns:
        Identity -> the literal to emit, aligned to the mapping where possible.
    """
    from coa_ontology.inducer.strategies.base import table_identity

    if not mapping_table_names:
        return logical_names
    # Mapping literals grouped by their bare table segment, for the reverse skew.
    by_bare: dict[str, list[str]] = {}
    for literal in mapping_table_names:
        by_bare.setdefault(split_sql_ident_path(literal)[-1], []).append(literal)

    aligned: dict[str, str] = {}
    for table in tables:
        identity = table_identity(table)
        derived = logical_names.get(identity) or _sql_ident(table.name)
        candidates = [derived, _sql_ident(table.name)]
        same_bare = by_bare.get(table.name, [])
        if len(same_bare) == 1:
            candidates.append(same_bare[0])
        chosen = next((c for c in candidates if c in mapping_table_names), None)
        if chosen is None:
            _log.warning(
                "schema.sql: table %s is not named by the mapping being stored beside it "
                "(mapping declares %s); emitting the catalog-derived name %s",
                table.name,
                sorted(same_bare) or "no matching logical table",
                derived,
            )
            chosen = derived
        elif chosen != derived:
            # WARNING, not info: chosen != derived means the STORED mapping names
            # this table differently from what the current catalog would derive —
            # i.e. a persisted rr:tableName whose shape differs from today's rule.
            # That is the exact signal an operator needs when diagnosing a
            # namespace accepted under an older qualification rule (see the
            # byte-identical-relative-to-pre-#149 note in the MR). (_align_to_mapping
            # has no namespace/ontology_id in scope; the caller logs those around
            # generation.)
            _log.warning(
                "schema.sql: mapping's stored logical name %s for table %s differs from the "
                "catalog-derived name %s — persisted mapping shape differs from the current rule",
                chosen,
                table.name,
                derived,
            )
        aligned[identity] = chosen
    return aligned


def _tables_to_h2_ddl(tables: list, mapping_table_names: set[str] | None = None) -> str:
    """Convert CatalogTable list to H2-compatible CREATE TABLE statements.

    Table and column names are emitted verbatim as SQL-delimited (double-quoted)
    identifiers via :func:`sql_ident`. Double-quoting lets H2 accept any source
    name — spaces, parens, percent signs, hyphens, mixed case, reserved words —
    so the identifiers exactly match the source datasource (and therefore the
    R2RML ``rr:tableName`` / ``rr:column`` values that Ontop validates against
    this schema). No canonicalization or uppercasing is applied.

    A table whose bare name is shared by two datasources is created inside its own
    H2 schema, matching the qualified ``rr:tableName`` the mapping emits for it
    (:func:`logical_table_names`). Without that, ``CREATE TABLE IF NOT EXISTS``
    silently skipped the second same-named table and Ontop validated BOTH
    TriplesMaps against the first table's columns. Table names that are
    unique in the run are emitted bare, exactly as before.

    Args:
        tables: Tables to describe.
        mapping_table_names: ``rr:tableName`` literals from the mapping this schema
            will validate, when known. Supplying them makes the DDL a function of
            the mapping rather than a second, independently-derived guess at the
            same names — see :func:`_align_to_mapping`.

    Returns:
        The H2 DDL text.
    """
    from coa_ontology.inducer.strategies.base import logical_table_names, table_identity

    logical_names = _align_to_mapping(logical_table_names(tables), tables, mapping_table_names)
    lines = ["-- Auto-generated schema for Ontop H2 validation (from datasource catalog)"]
    # H2 rejects a qualified CREATE TABLE whose schema does not exist yet, so every
    # schema a qualified name references is declared up front. The schema is taken
    # from the parsed identifier path, not by splitting on the last dot: a table
    # genuinely named ``q1.results`` is ONE identifier (``"q1.results"``), and
    # splitting it textually emitted ``CREATE SCHEMA IF NOT EXISTS "q1;`` —
    # unbalanced quotes that make the entire schema.sql a syntax error, so Ontop
    # validates the mapping against nothing at all.
    schemas = sorted(
        {parts[0] for parts in (split_sql_ident_path(n) for n in logical_names.values()) if len(parts) > 1}
    )
    lines += [f"CREATE SCHEMA IF NOT EXISTS {_sql_ident(s)};" for s in schemas]
    # Identity breaks the tie: two same-named tables would otherwise be ordered by
    # the arrival order of a set() of datasource ids, so the emitted DDL differed
    # run to run for no reason.
    emitted: dict[str, list[str]] = {}
    for table in sorted(tables, key=lambda t: (t.name, table_identity(t))):
        col_defs = []
        pk_cols = []
        if table.tableConstraints:
            for tc in table.tableConstraints:
                if tc.constraintType == "PRIMARY_KEY":
                    pk_cols = tc.columns
        for col in table.columns:
            h2_type = _CATALOG_TO_H2.get(col.dataType.split("(")[0].upper(), "VARCHAR(255)")
            col_def = f"{_sql_ident(col.name)} {h2_type}"
            if col.name in pk_cols:
                col_def += " NOT NULL"
            col_defs.append(col_def)
        if pk_cols:
            pk_quoted = ", ".join(_sql_ident(c) for c in pk_cols)
            col_defs.append(f"PRIMARY KEY ({pk_quoted})")
        logical = logical_names.get(table_identity(table)) or _sql_ident(table.name)
        # One CREATE per logical name. Two tables can legitimately share one — the
        # mapping itself declares one logical table for both when their bare name
        # was unique in each of the runs that produced them — and H2 makes the
        # repeat a silent no-op, so emitting it would look like two declarations
        # while behaving as one. Say so instead: the second table's columns are NOT
        # what Ontop will validate against.
        if logical in emitted:
            if emitted[logical] != col_defs:
                _log.warning(
                    "schema.sql: table %s shares the logical name %s with an earlier table but has "
                    "different columns; Ontop will validate BOTH mappings against the first (%s)",
                    table.name,
                    logical,
                    emitted[logical],
                )
            else:
                _log.info("schema.sql: table %s duplicates the logical name %s; declared once", table.name, logical)
            continue
        emitted[logical] = col_defs
        lines.append(f"CREATE TABLE IF NOT EXISTS {logical} ({', '.join(col_defs)});")
    # Coverage guard: the merged mapping is the concatenation of every accepted
    # proposal's STORED r2rml (see _persist_induced_to_s3), so it can declare more
    # rr:tableName literals than there are physical tables in the current catalog —
    # e.g. a namespace holding one proposal accepted while a name was qualified and
    # another accepted while it was bare. Ontop validates the mapping against THIS
    # schema, so any literal without a CREATE fails VKG load for the WHOLE namespace,
    # not just that table. Emit a CREATE for every still-undeclared literal, reusing
    # the column defs of the table whose bare name matches (IF NOT EXISTS makes an
    # extra declaration free); raise if a literal names a table we cannot describe,
    # so the failure is loud at generation time rather than silent at VKG load.
    if mapping_table_names:
        cols_by_bare: dict[str, list[str]] = {}
        for logical, col_defs in emitted.items():
            cols_by_bare.setdefault(split_sql_ident_path(logical)[-1], col_defs)
        undeclared = sorted(set(mapping_table_names) - set(emitted))
        uncoverable: list[str] = []
        extra_schemas: list[str] = []
        extra_tables: list[str] = []
        for literal in undeclared:
            parts = split_sql_ident_path(literal)
            literal_cols = cols_by_bare.get(parts[-1])
            if literal_cols is None:
                uncoverable.append(literal)
                continue
            if len(parts) > 1 and parts[0] not in schemas:
                extra_schemas.append(parts[0])
            extra_tables.append(f"CREATE TABLE IF NOT EXISTS {literal} ({', '.join(literal_cols)});")
            emitted[literal] = literal_cols
        if uncoverable:
            raise SchemaSqlGenerationError(
                "mapping declares rr:tableName literal(s) with no matching physical table, "
                f"so schema.sql cannot cover them and Ontop would reject the namespace: {uncoverable}"
            )
        for s in sorted(set(extra_schemas)):
            # Insert schema declarations after the initial comment + existing schema
            # block so a qualified extra literal has its schema created first.
            decl = f"CREATE SCHEMA IF NOT EXISTS {_sql_ident(s)};"
            if decl not in lines:
                lines.insert(1, decl)
        lines += extra_tables
    return "\n".join(lines)


def _clean_ontology_for_vkg(turtle: str, r2rml_turtle: str | None = None) -> str:
    """Strip OWL constructs incompatible with Ontop's OWL 2 QL profile.

    Removes:
    - rdf:Property type assertions (redundant; Ontop needs only owl:ObjectProperty/DatatypeProperty)
    - owl:hasKey axioms (not in OWL 2 QL, and blank-node lists confuse Ontop)
    - Internal workbench metadata triples (ontology-workbench.local/vocab#)
    - coa:suggestedSubClassOf and coa:suggestionReason (proposal-internal; never meaningful to Ontop)
    - Preserves temporal ranges (xsd:date/dateTime/time) — they match R2RML
    - Aligns property ranges with R2RML rr:datatype declarations (prevents MappingOntologyMismatchException)
    """
    from rdflib import OWL, RDF, RDFS, XSD, Graph, Namespace, URIRef

    WB = Namespace("https://ontology-workbench.local/vocab#")
    RR = Namespace("http://www.w3.org/ns/r2rml#")

    g = Graph()
    try:
        g.parse(data=turtle, format="turtle")
    except Exception:
        # If we can't parse, return as-is (best effort)
        return turtle

    # Canonicalize malformed / mis-cased / aliased XSD datatype tokens FIRST, so
    # the exact-cased date/time normalization below actually matches them. Without
    # this, a lowercase ``xsd:datetime`` (or ``xsd:varchar`` etc.) reaches Ontop as
    # an undefined datatype — it slips past the ``(XSD.dateTime, XSD.date,
    # XSD.time)`` match, which is case-sensitive. This is the accept-time SAFETY
    # NET for the served VKG copy: the interactive edit path no longer canonicalizes
    # (user data is persisted verbatim + surfaced for consent-gated repair), so this
    # is what guarantees a *skipped* repair can't push a malformed token to Ontop.
    from coa_ontology.datatype_canonicalizer import canonicalize_datatypes

    changes = canonicalize_datatypes(g)
    if changes:
        _log.info("VKG datatype canonicalization rewrote %d token(s): %s", len(changes), changes)

    # Strip owl:imports (boundary defense for uploaded ontologies): Ontop/OWLAPI
    # network-resolves each import at VKG load and fails every query on a
    # non-dereferenceable foundational URI. Grounding survives via the
    # rdfs:subClassOf + skos:* / coa:groundedTo axioms already in the graph.
    for s, p, o in list(g.triples((None, OWL.imports, None))):
        g.remove((s, p, o))

    # Remove rdf:Property declarations (keep only owl:ObjectProperty / owl:DatatypeProperty)
    for s in list(g.subjects(RDF.type, RDF.Property)):
        g.remove((s, RDF.type, RDF.Property))

    # Remove owl:hasKey axioms and their associated blank-node lists
    for s, p, o in list(g.triples((None, OWL.hasKey, None))):
        _remove_rdf_list(g, o)
        g.remove((s, p, o))

    # Remove workbench-internal metadata
    for s, p, o in list(g.triples((None, None, None))):
        if str(p).startswith(str(WB)):
            g.remove((s, p, o))

    # Strip proposal-internal suggestion triples — these are never meaningful
    # to Ontop/VKG and should not survive into the accepted ontology. Any
    # suggestion the user confirmed was already promoted to rdfs:subClassOf
    # via the UI's save flow before accept was called.
    SCL = Namespace(VOCAB_URI)
    for s, p, o in list(g.triples((None, SCL.suggestedSubClassOf, None))):
        g.remove((s, p, o))
    for s, p, o in list(g.triples((None, SCL.suggestionReason, None))):
        g.remove((s, p, o))

    # Resolve dual-typed properties: if both ObjectProperty and DatatypeProperty,
    # keep only ObjectProperty (OWL 2 QL requires exclusive typing).
    obj_props = set(g.subjects(RDF.type, OWL.ObjectProperty))
    data_props = set(g.subjects(RDF.type, OWL.DatatypeProperty))
    for prop in obj_props & data_props:
        g.remove((prop, RDF.type, OWL.DatatypeProperty))
        for _, _, o in list(g.triples((prop, RDFS.range, None))):
            if str(o).startswith(str(XSD)):
                g.remove((prop, RDFS.range, o))

    # Temporal ranges are left INTACT. They used to be rewritten to xsd:string
    # to match the R2RML rr:datatype, which itself only said xsd:string because
    # the H2 validation schema declared temporal columns as VARCHAR. All three
    # layers now carry the real type, so the alignment below is satisfied
    # without discarding it. Rewriting them made every date FILTER
    # unsatisfiable — see the _CATALOG_TO_H2 comment above.

    # Align ontology property ranges with R2RML rr:datatype declarations.
    # Ontop is strict: if the R2RML says xsd:decimal but the ontology says
    # xsd:string, translation fails with MappingOntologyMismatchException.
    if r2rml_turtle:
        try:
            from coa_ontology.datatype_canonicalizer import _canonical_for

            r2rml_g = Graph()
            r2rml_g.parse(data=r2rml_turtle, format="turtle")
            # Build map: property IRI → rr:datatype from R2RML
            r2rml_datatypes: dict[str, URIRef] = {}
            for pom in r2rml_g.subjects(RR.predicate, None):
                predicate = r2rml_g.value(pom, RR.predicate)
                obj_map = r2rml_g.value(pom, RR.objectMap)
                if predicate and obj_map:
                    datatype = r2rml_g.value(obj_map, RR.datatype)
                    if datatype:
                        # Canonicalize the R2RML token here too: this alignment step
                        # copies rr:datatype into the served ontology range, so a
                        # malformed rr:datatype (e.g. xsd:datetime) would re-inject an
                        # undefined datatype into the VKG copy AFTER the graph-level
                        # canonicalize above already cleaned it. _canonical_for returns
                        # None for already-valid/unknown tokens → keep the original.
                        dt_ref = URIRef(str(datatype))
                        r2rml_datatypes[str(predicate)] = _canonical_for(dt_ref) or dt_ref

            # Update ontology ranges to match R2RML datatypes
            for prop_iri, expected_dt in r2rml_datatypes.items():
                prop_ref = URIRef(prop_iri)
                current_ranges = list(g.objects(prop_ref, RDFS.range))
                if not current_ranges:
                    continue
                for current_range in current_ranges:
                    if str(current_range).startswith(str(XSD)) and current_range != expected_dt:
                        g.remove((prop_ref, RDFS.range, current_range))
                        g.add((prop_ref, RDFS.range, expected_dt))
        except Exception as e:
            # Best effort — don't break publish if R2RML parsing/alignment fails.
            # Bind the exception type + message (in addition to exc_info) so a code
            # bug in the canonicalization above is greppable and distinguishable from
            # a user-fixable parse error, not just a bare "skipped" line.
            _log.warning("r2rml_range_alignment_skipped: %s: %s", type(e).__name__, e, exc_info=True)

    return g.serialize(format="turtle")


def _remove_rdf_list(g, node) -> None:
    """Recursively remove an RDF list (rdf:first/rdf:rest chain)."""
    from rdflib import RDF, URIRef

    if node == RDF.nil or isinstance(node, URIRef):
        return
    first_val = g.value(node, RDF.first)
    rest_val = g.value(node, RDF.rest)
    g.remove((node, RDF.first, first_val))
    g.remove((node, RDF.rest, rest_val))
    if rest_val and rest_val != RDF.nil:
        _remove_rdf_list(g, rest_val)


def _persist_induced_to_s3(
    ontology_id: str, namespace: str, graph_uri: str, current_datasource_ids: list[str] | None = None
) -> None:
    """Persist the full induced ontology + accumulated R2RML to S3.

    Called after each proposal accept. Fetches the current full state:
    - Ontology Turtle from Neptune (the named graph is the source of truth,
      accumulates across all accepted proposals for this ontology)
    - R2RML from all accepted proposals targeting this ontology (concatenated)

    Writes to:
      s3://{bucket}/{prefix}/{namespace}/induced/{safe_id}.ttl
      s3://{bucket}/{prefix}/{namespace}/induced/{safe_id}.r2rml.ttl
      s3://{bucket}/{prefix}/{namespace}/latest/ontology.ttl       (VKG consumption)
      s3://{bucket}/{prefix}/{namespace}/latest/mappings.r2rml     (VKG consumption)
    """
    import boto3

    from coa_ontology.stores.neptune_db_graph import _gsp_get_turtle

    try:
        # 1. Get full ontology turtle from Neptune named graph
        ontology_turtle = _gsp_get_turtle(graph_uri) if graph_uri else None
        if not ontology_turtle:
            _log.warning("s3 persist: no turtle from graph %s, skipping", graph_uri)
            return

        # 2. Accumulate R2RML from all accepted proposals for this ontology
        accepted = dynamo_store.list_proposals(
            namespace=namespace, ontology_id=ontology_id, status=ProposalStatus.ACCEPTED.value
        )
        r2rml_parts = []
        prefixes_seen: set[str] = set()
        for p in accepted:
            r2rml = p.get("r2rml_turtle", "")
            if not r2rml and p.get("r2rml_s3_key"):
                r2rml = dynamo_store._get_artifact_s3(namespace, p["proposal_id"], "r2rml") or ""
            if not r2rml:
                continue
            # Deduplicate @prefix lines across proposals
            lines = []
            for line in r2rml.split("\n"):
                if line.strip().startswith("@prefix"):
                    if line.strip() not in prefixes_seen:
                        prefixes_seen.add(line.strip())
                        lines.append(line)
                else:
                    lines.append(line)
            r2rml_parts.append("\n".join(lines))
        r2rml_turtle = "\n\n".join(r2rml_parts) if r2rml_parts else None

        # Deduplicate R2RML TriplesMaps: multiple proposals for the same ontology
        # can contribute identical TriplesMap definitions. Ontop rejects R2RML with
        # duplicate logicalTable nodes on the same TriplesMap subject.
        if r2rml_turtle:
            try:
                from rdflib import Graph
                from rdflib import Namespace as RdfNamespace

                RR = RdfNamespace("http://www.w3.org/ns/r2rml#")
                r2rml_g = Graph()
                r2rml_g.parse(data=r2rml_turtle, format="turtle")
                for tmap in r2rml_g.subjects(predicate=None, object=RR.TriplesMap):
                    lts = list(r2rml_g.objects(tmap, RR.logicalTable))
                    if len(lts) > 1:
                        for lt in lts[1:]:
                            r2rml_g.remove((tmap, RR.logicalTable, lt))
                            for tn in r2rml_g.objects(lt, RR.tableName):
                                r2rml_g.remove((lt, RR.tableName, tn))
                r2rml_turtle = r2rml_g.serialize(format="turtle")
            except Exception:
                # Best effort — don't break persist if dedup fails.
                _log.warning("r2rml_triplesmap_dedup_skipped", exc_info=True)

        # 3. Write to S3
        short_id = _ontology_short_id(ontology_id)

        s3 = boto3.client("s3", region_name=os.environ.get("AWS_REGION", "us-east-1"))
        base_key = f"{_S3_PREFIX}/{namespace}/induced/{short_id}"

        s3.put_object(
            Bucket=_S3_BUCKET,
            Key=f"{base_key}.ttl",
            Body=ontology_turtle.encode("utf-8"),
            ContentType="text/turtle",
        )
        _log.info("s3 persist: wrote %s.ttl (%d bytes)", base_key, len(ontology_turtle))

        if r2rml_turtle:
            s3.put_object(
                Bucket=_S3_BUCKET,
                Key=f"{base_key}.r2rml.ttl",
                Body=r2rml_turtle.encode("utf-8"),
                ContentType="text/turtle",
            )
            _log.info("s3 persist: wrote %s.r2rml.ttl (%d bytes)", base_key, len(r2rml_turtle))

        # 4. Write to the VKG-expected "latest/" path so the VKG service
        #    can discover and load the ontology + mappings at startup.
        #    The VKG ontology is cleaned for OWL 2 QL compatibility (Ontop).
        latest_key = f"{_S3_PREFIX}/{namespace}/latest"
        vkg_turtle = _clean_ontology_for_vkg(ontology_turtle, r2rml_turtle=r2rml_turtle)
        s3.put_object(
            Bucket=_S3_BUCKET,
            Key=f"{latest_key}/ontology.ttl",
            Body=vkg_turtle.encode("utf-8"),
            ContentType="text/turtle",
        )
        _log.info("s3 persist: wrote %s/ontology.ttl (%d bytes)", latest_key, len(vkg_turtle))

        if r2rml_turtle:
            s3.put_object(
                Bucket=_S3_BUCKET,
                Key=f"{latest_key}/mappings.r2rml",
                Body=r2rml_turtle.encode("utf-8"),
                ContentType="text/turtle",
            )
            _log.info("s3 persist: wrote %s/mappings.r2rml (%d bytes)", latest_key, len(r2rml_turtle))

        # 5. Generate and upload schema.sql from datasource catalog.
        #    Ontop needs schema.sql to validate R2RML column references at startup.
        #    Identifiers are emitted verbatim (SQL-delimited), so they match the
        #    source datasource directly — no canonical→original column map needed.
        #
        #    A generation failure is logged at ERROR but kept best-effort: the
        #    rest of the VKG payload is already written. (Failing the whole accept
        #    on this is coupled to the accept-flow ordering rework — #467.)
        try:
            schema_sql = _generate_schema_sql(
                namespace, ontology_id, r2rml_turtle, extra_datasource_ids=current_datasource_ids
            )
        except SchemaSqlGenerationError as e:
            schema_sql = None
            _log.error(
                "s3 persist: schema.sql generation FAILED for %s (ns=%s) — Ontop R2RML "
                "column validation will be degraded until re-accept: %s",
                ontology_id,
                namespace,
                e,
            )
        if schema_sql:
            s3.put_object(
                Bucket=_S3_BUCKET,
                Key=f"{latest_key}/schema.sql",
                Body=schema_sql.encode("utf-8"),
                ContentType="text/sql",
            )
            _log.info("s3 persist: wrote %s/schema.sql (%d bytes)", latest_key, len(schema_sql))
    except Exception:
        # RAISE — do NOT swallow (#467). Warning-and-returning here hid a
        # Neptune<->S3 split-brain: the graph is committed and DDB says
        # ``accepted``, but VKG keeps serving the stale ``latest/`` copy with no
        # signal. The caller retries this as the ``s3_persist`` step and logs
        # each attempt, so no log line is needed here.
        raise


def _emit_ontology_published(namespace: str, version: str) -> bool:
    """Emit ontology.published event to EventBridge so VKG reloads.

    RAISES on failure, including a partial ``FailedEntryCount`` (which is a
    per-entry failure EventBridge reports in a 200 response, so it must be
    checked explicitly). As with :func:`_reconcile_counts`, non-fatality is the
    CALLER's declaration via ``_run_accept_step(..., fatal=False)`` — swallowing
    here would mean a single transient ``PutEvents`` blip became a permanent
    skip instead of being retried 3×.

    Why the caller declares it non-fatal (#467): losing this event means S3 holds
    the correct new ontology while the VKG service keeps serving the previous
    payload — real user-visible staleness (Tier-2 answers from the old mappings,
    with no error raised), but the ontology itself is complete and correct, so it
    is not worth failing an otherwise-perfect accept. It is its OWN pipeline step
    (was a silent tail-call inside :func:`_persist_induced_to_s3`), so an
    exhausted retry is recorded as
    ``accept_progress {step: notify_vkg, state: skipped}`` and is greppable.

    GAP (#851): a skipped notify_vkg has no in-product recovery — re-accept
    returns early on ``accepted`` and cannot re-emit. Today an operator forces a
    new VKG ECS deployment. The EventBridge retry/alarm only cover delivery of an
    event that reached EventBridge, not a ``put_events`` that never succeeded.
    """
    import boto3

    events_client = boto3.client("events", region_name=os.environ.get("AWS_REGION", "us-east-1"))
    resp = events_client.put_events(
        Entries=[
            {
                "Source": f"{EVENT_SOURCE_PREFIX}.ontology",
                "DetailType": "ontology.published",
                "Detail": json.dumps(
                    {
                        "namespace": namespace,
                        "version": version,
                        "s3Bucket": _S3_BUCKET,
                        "s3Prefix": f"{_S3_PREFIX}/{namespace}/latest/",
                    }
                ),
            }
        ]
    )
    failed = resp.get("FailedEntryCount", 0)
    if failed:
        raise RuntimeError(f"put_events reported FailedEntryCount={failed}: {resp.get('Entries')}")
    _log.info("eventbridge: emitted ontology.published for namespace=%s version=%s", namespace, version)
    return True


