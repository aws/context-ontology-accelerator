def _build_embedding_text(label: str, description: str) -> str:
    """Produce the canonical input text for the embedding model.

    Per Requirement 9.8 the embedding is computed over both the class
    label AND the generated description, concatenated as
    ``"{label}: {description}"`` so semantically similar classes with
    different surface labels still match.

    A blank description is permitted (the embedding then reduces to
    just the label, which still produces a valid vector but loses the
    semantic boost from the description).

    Args:
        label: The class label (e.g. ``"Person"``).
        description: The generated rdfs:comment-style description.

    Returns:
        The text to be embedded.
    """
    description = description.strip() if description else ""
    if description:
        return f"{label}: {description}"
    return label


def _band_for_score(score: float) -> MatchBand:
    """Bucket a cosine similarity into one of the three match bands."""
    if score >= EXACT_THRESHOLD:
        return "exact"
    if score >= CLOSE_MATCH_THRESHOLD:
        return "close_match"
    return "novel"


def _cosine(a: list[float], b: list[float]) -> float:
    """Cosine similarity between two vectors, robust to non-unit norms.

    For unit-length vectors this reduces to a dot product. Falls back
    to explicit normalization when the inputs are not unit-length so a
    caller using non-Bedrock embeddings still gets correct values.

    Returns ``0.0`` for any malformed input (empty, mismatched length,
    or zero-norm vectors).
    """
    if not a or not b or len(a) != len(b):
        return 0.0
    dot = 0.0
    norm_a_sq = 0.0
    norm_b_sq = 0.0
    for x, y in zip(a, b, strict=True):
        dot += x * y
        norm_a_sq += x * x
        norm_b_sq += y * y
    if norm_a_sq <= 0.0 or norm_b_sq <= 0.0:
        return 0.0
    if abs(norm_a_sq - 1.0) < 1e-6 and abs(norm_b_sq - 1.0) < 1e-6:
        return dot
    return dot / (math.sqrt(norm_a_sq) * math.sqrt(norm_b_sq))


def _embed_with_cache(
    embedding_client: ClassEmbeddingClient,
    index: InMemoryClassEmbeddingIndex,
    text: str,
) -> list[float]:
    """Embed ``text``, consulting/populating the index's embed_cache.

    Saves a Bedrock round-trip when the same embedding text appears
    multiple times in a single ``normalize`` call (or across calls
    sharing the same index).
    """
    cached = index.embed_cache.get(text)
    if cached is not None:
        return cached
    vector = embedding_client.embed_text(text)
    index.embed_cache[text] = vector
    return vector


