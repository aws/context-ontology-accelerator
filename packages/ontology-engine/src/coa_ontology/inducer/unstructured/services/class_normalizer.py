def normalize(
    classes: dict[str, str],
    embedding_client: ClassEmbeddingClient,
    iri_resolver: IRIResolver,
    *,
    index: InMemoryClassEmbeddingIndex | None = None,
    source_mode: str | None = None,
) -> dict[str, NormalizationResult]:
    """Normalize each class label against the running embedding index.

    For each ``(label, description)`` pair, in iteration order:

    1. Reuse a deterministic label-key match when one exists.
    2. Build the embedding text via :func:`_build_embedding_text`.
    3. Embed it via ``embedding_client.embed_text`` (with caching).
    4. Run a top-1 cosine kNN against the running ``index``.
    5. Bucket the top hit into a :class:`MatchBand`.
    6. For ``exact``: reuse ``hit.iri``; do NOT add to the index.
       For ``close_match`` / ``novel``: mint a fresh IRI via
       ``iri_resolver.resolve(label, "class")`` (the literal ``"class"``
       token disambiguates T-Box class IRIs from A-Box individual IRIs;
       see Req 10.2) and add the new entry to the index so subsequent
       classes in the same call (or later calls sharing the index)
       can match against it.

    Per-class fault isolation: any exception from the embedding client
    or the IRI resolver is caught, logged at WARNING level, and the
    affected class is treated as ``novel`` with score ``0.0``. The
    affected entry is NOT added to the index (since we have no vector
    for it). Programmer errors (e.g. wrong types) propagate.

    Args:
        classes: Mapping from class label (e.g. ``"Person"``) to its
            generated description. Either may be empty.
        embedding_client: Object satisfying :class:`ClassEmbeddingClient`.
        iri_resolver: The
            :class:`~coa_ontology.inducer.unstructured.services.iri_resolver.IRIResolver`
            used to mint new IRIs for ``close_match`` / ``novel`` bands.
        index: An :class:`InMemoryClassEmbeddingIndex`, possibly already
            populated from prior calls. If ``None`` a fresh empty index
            is created and discarded after the call. **Pass an explicit
            instance to share state across calls.**
        source_mode: Free-form string identifying the description mode
            for downstream traceability. Common values:
            ``"none"`` / ``"instance"`` / ``"schema"`` / ``None``.

    Returns:
        Mapping from each input class label to a
        :class:`NormalizationResult`. Keys exactly match the input keys.
    """
    if index is None:
        index = InMemoryClassEmbeddingIndex()

    log.info(
        "Normalizing %d classes against in-memory index (initial size=%d, source_mode=%s)",
        len(classes),
        len(index),
        source_mode,
    )

    results: dict[str, NormalizationResult] = {}

    for label, description in classes.items():
        deterministic_match = index.find_by_label(label)
        if deterministic_match is not None:
            preferred_label = deterministic_match.label
            results[label] = NormalizationResult(
                class_iri=deterministic_match.iri,
                band="exact",
                # 1.0 is asserted, not measured: this path never embeds, so
                # no cosine exists. The lookup key is a stricter identity
                # test than the 0.95 cosine threshold, so reporting the
                # band's ceiling keeps the field monotonic with confidence.
                # Consumers that need a measured score must filter on
                # ``source_mode``/band rather than reading this as a cosine.
                similarity_score=1.0,
                matched_existing_iri=deterministic_match.iri,
                source_mode=source_mode,
                preferred_label=preferred_label,
                alternative_labels=(label,) if label != preferred_label else (),
            )
            log.debug(
                "Class %r: deterministic label match %r — exact",
                label,
                preferred_label,
            )
            continue

        text = _build_embedding_text(label, description)
        log.debug(
            "Class %r: embedding %d-char text (index size=%d)",
            label,
            len(text),
            len(index),
        )

        # Embed.
        try:
            vector = _embed_with_cache(embedding_client, index, text)
        except Exception as exc:  # noqa: BLE001
            log.warning(
                "Embedding failed for class %r (%s: %s) — treating as novel without adding to index",
                label,
                type(exc).__name__,
                exc,
            )
            results[label] = _resolve_novel(
                label,
                iri_resolver,
                score=0.0,
                source_mode=source_mode,
                index_to_update=None,  # nothing to add — we have no vector
                description=description,
            )
            continue

        # Top-1 kNN against everything seen so far.
        hits = index.top_k(vector, k=1)
        if not hits:
            # Empty index: this class is novel by definition.
            log.debug("Class %r: index empty — novel (first class seen)", label)
            results[label] = _resolve_novel(
                label,
                iri_resolver,
                score=0.0,
                source_mode=source_mode,
                index_to_update=index,
                vector=vector,
                description=description,
            )
            continue

        score, top = hits[0]
        band = _band_for_score(score)
        matched_iri = top.iri or None
        log.debug(
            "Class %r: top match label=%r iri=%s score=%.4f band=%s",
            label,
            top.label,
            matched_iri,
            score,
            band,
        )

        if band == "exact":
            # Reuse the existing IRI. Do NOT add to the index — the
            # existing entry already represents this class.
            results[label] = NormalizationResult(
                class_iri=matched_iri or "",
                band="exact",
                similarity_score=score,
                matched_existing_iri=matched_iri,
                source_mode=source_mode,
                preferred_label=top.label,
                alternative_labels=(label,) if label != top.label else (),
            )
            continue

        # close_match (Req 9.4) or novel (Req 9.5): mint and add to index.
        try:
            # Per Req 10.2, class IRIs use the literal token ``"class"``
            # in the classification slot — distinguishes T-Box class IRIs
            # from A-Box individual IRIs that would otherwise collide
            # when an entity is literally named "Person" of class Person.
            class_iri = iri_resolver.resolve(label, "class")
        except Exception as exc:  # noqa: BLE001
            log.warning(
                "IRI resolver failed for class %r (%s: %s) — returning novel with empty class_iri",
                label,
                type(exc).__name__,
                exc,
            )
            results[label] = NormalizationResult(
                class_iri="",
                band="novel",
                similarity_score=0.0,
                matched_existing_iri=None,
                source_mode=source_mode,
                preferred_label=label,
            )
            continue

        # Add the new (label, vector, iri) to the index so subsequent
        # classes can match against it.
        index.add(
            label=label,
            description=description,
            vector=vector,
            iri=class_iri,
        )

        results[label] = NormalizationResult(
            class_iri=class_iri,
            band=band,
            similarity_score=score,
            # Per spec Req 9.5: novel = "no link to existing classes",
            # so we don't surface the matched_existing_iri there.
            matched_existing_iri=matched_iri if band == "close_match" else None,
            source_mode=source_mode,
            preferred_label=label,
        )

    log.info(
        "Normalization complete: final index size=%d (entries added this call=%d)",
        len(index),
        sum(1 for r in results.values() if r.band in ("close_match", "novel") and r.class_iri),
    )

    return results


def _resolve_novel(
    label: str,
    iri_resolver: IRIResolver,
    *,
    score: float,
    source_mode: str | None,
    index_to_update: InMemoryClassEmbeddingIndex | None,
    description: str = "",
    vector: list[float] | None = None,
) -> NormalizationResult:
    """Helper for the empty-index and embed-failure paths.

    Mints a fresh IRI and (if ``index_to_update`` is non-None and
    ``vector`` was provided) adds the new entry to the index. If the
    resolver itself fails, returns an empty class_iri so the caller
    can detect the hard failure.
    """
    try:
        # Per Req 10.2, class IRIs use the literal token ``"class"`` in
        # the classification slot.
        class_iri = iri_resolver.resolve(label, "class")
    except Exception as exc:  # noqa: BLE001
        log.warning(
            "IRI resolver failed during novel mint for class %r (%s: %s) — returning empty class_iri",
            label,
            type(exc).__name__,
            exc,
        )
        return NormalizationResult(
            class_iri="",
            band="novel",
            similarity_score=score,
            matched_existing_iri=None,
            source_mode=source_mode,
            preferred_label=label,
        )

    if index_to_update is not None and vector:
        index_to_update.add(
            label=label,
            description=description,
            vector=vector,
            iri=class_iri,
        )

    return NormalizationResult(
        class_iri=class_iri,
        band="novel",
        similarity_score=score,
        matched_existing_iri=None,
        source_mode=source_mode,
        preferred_label=label,
    )
