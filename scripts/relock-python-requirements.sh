# Re-lock the hash-pinned requirements a Python Lambda bundle installs from.
#
# A package's requirements.txt keeps the human-edited direct dependencies and
# their floors. requirements.lock.txt next to it pins the whole tree with
# hashes, and infra/lib/utils/python-bundling.ts installs the bundle from the
# lock with --require-hashes, so two deploys of one commit ship the same
# dependencies and an upstream release cannot change a deploy (#1376).
#
# Relock after editing requirements.txt, or after bumping a pin in the lock:
# the existing pins are kept as preferences, so only what the edit requires
# moves. Renovate runs this as a postUpgradeTask (renovate.json), so its MRs
# for these files are mergeable as opened.
#
# Usage:
#   scripts/relock-python-requirements.sh            # relock every package below
#   scripts/relock-python-requirements.sh --check    # verify only, write nothing:
#       the lock is what this script would write from requirements.txt, and
#       x86_64 and arm64 resolve to the same pins (one lock serves both).
#
# Requires uv; 0.13.4 is fetched with `uv tool run` if the one on PATH differs.

set -euo pipefail

MODE=relock
case "${1:-}" in
  '')        MODE=relock ;;
  --check)   MODE=check ;;
  -h|--help) sed -n '2,24p' "$0" | sed 's|^# \{0,1\}||'; exit 0 ;;
  *)         echo "relock-python-requirements: unknown argument '$1' (expected --check or no argument)" >&2; exit 2 ;;
esac

# Packages whose Lambda bundles install from a lock. Add one here when its
# bundles move to requirements.lock.txt.
PACKAGES=(packages/sources)

UV_VERSION=0.13.4
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
cd "$REPO_ROOT"

if [ "$(uv --version 2>/dev/null | awk '{print $2}')" = "$UV_VERSION" ]; then
  UV=(uv)
else
  UV=(uv tool run "uv@$UV_VERSION")
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# Compile $1/requirements.txt for one Lambda platform into $3, keeping the pins
# already in $3 as preferences. The project's [tool.uv] constraints apply, so
# the security floors it declares carry into the lock.
compile() {
  local pkg="$1" platform="$2" out="$3"
  "${UV[@]}" pip compile "$pkg/requirements.txt" \
    --python-platform "$platform" --python-version 3.12 \
    --only-binary :all: --generate-hashes --no-header --quiet \
    --output-file "$out"
}

# The lock as this script writes it: a fixed header, then uv's output.
render() {
  local pkg="$1" body="$2" out="$3"
  {
    echo "# Generated by scripts/relock-python-requirements.sh from $pkg/requirements.txt."
    echo "# Do not edit by hand: edit requirements.txt (or a pin here), then run the script."
    echo "# Installed with --require-hashes by infra/lib/utils/python-bundling.ts."
    cat "$body"
  } > "$out"
}

pins() { grep -E '^[A-Za-z0-9_.-]+==' "$1" | sed 's/ \\$//' ; }

status=0
for pkg in "${PACKAGES[@]}"; do
  lock="$pkg/requirements.lock.txt"
  work="$TMP/$(echo "$pkg" | tr '/' '_')"
  mkdir -p "$work"
  # Seed the preferences with the current lock, if any.
  if [ -f "$lock" ]; then cp "$lock" "$work/x86.txt"; cp "$lock" "$work/arm.txt"; fi
  compile "$pkg" x86_64-manylinux2014 "$work/x86.txt"
  compile "$pkg" aarch64-manylinux2014 "$work/arm.txt"

  if ! diff <(pins "$work/x86.txt") <(pins "$work/arm.txt") > "$work/arch.diff"; then
    echo "relock-python-requirements: $pkg resolves differently on x86_64 and arm64:" >&2
    cat "$work/arch.diff" >&2
    status=1
    continue
  fi
  render "$pkg" "$work/x86.txt" "$work/lock.txt"

  if [ "$MODE" = check ]; then
    if [ ! -f "$lock" ]; then
      echo "relock-python-requirements: $lock is missing; run scripts/relock-python-requirements.sh" >&2
      status=1
    elif ! diff -u "$lock" "$work/lock.txt" > "$work/lock.diff"; then
      echo "relock-python-requirements: $lock is out of date with $pkg/requirements.txt; run scripts/relock-python-requirements.sh" >&2
      cat "$work/lock.diff" >&2
      status=1
    else
      echo "relock-python-requirements: $lock is up to date ($(pins "$lock" | wc -l | tr -d ' ') pins)"
    fi
  else
    cp "$work/lock.txt" "$lock"
    echo "relock-python-requirements: wrote $lock ($(pins "$lock" | wc -l | tr -d ' ') pins)"
  fi
done
exit "$status"
